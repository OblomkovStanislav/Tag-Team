/**
 * Менеджер звука.
 * Отвечает за загрузку, воспроизведение и выключение звуковых эффектов.
 * Поддерживает наложение звуков друг на друга.
 */
export class AudioManager {
    //Приватные свойства

    /**
     * Хранилище загруженных звуков.
     * Ключи — имена звуков, значения — HTML-элементы аудио.
     * @type {Object.<string, HTMLAudioElement>}
     */
    #sounds = {};

    /**
     * Флаг, выключен ли звук в данный момент.
     * @type {boolean}
     */
    #isMute = false;

    //Публичные свойства

    /**
     * Получить текущее состояние звука.
     * @returns {boolean} true, если звук выключен (mute).
     */
    get isMute() {
        return this.#isMute;
    }

    //Публичные методы

    /**
     * Добавляет звук в менеджер и начинает его предзагрузку.
     *
     * @param {string} src - Путь к аудиофайлу (например, "./sounds/click.mp3").
     * @param {string} name - Уникальное имя (ключ) для этого звука.
     */
    add(src, name) {
        const sound = new Audio(src);
        sound.preload = "auto"; // Просим браузер загрузить файл заранее
        this.#sounds[name] = sound;
    }

    /**
     * Удаляет звук из памяти.
     *
     * @param {string} name - Имя звука, который нужно удалить.
     */
    remove(name) {
        delete this.#sounds[name];
    }

    /**
     * Воспроизводит звук по его имени.
     * Создает клон аудио-объекта, чтобы звуки могли играть одновременно,
     * не прерывая друг друга.
     *
     * @param {string} name - Имя звука для воспроизведения.
     */
    play(name) {
        if (this.#isMute) return;

        const sound = this.#sounds[name];

        if (!sound) return;

        // Клонируем аудио, чтобы несколько вызовов play() могли звучать одновременно
        const clone = sound.cloneNode();

        clone.volume = 0.5; // Ограничиваем громкость, чтобы наложения не резали слух
        clone.currentTime = 0; // Начинаем с самого начала

        // .catch(() => {}) нужен, чтобы браузер (особенно Safari на iOS)
        // не выдавал ошибку в консоль, если звук заблокирован до клика пользователя
        clone.play().catch(() => {});
    }

    /**
     * Переключает режим "Без звука" (вкл/выкл).
     */
    mute() {
        this.#isMute = !this.#isMute;
    }
}